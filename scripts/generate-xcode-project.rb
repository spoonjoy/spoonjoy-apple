def swift_sources_under(relative_dir)
  root = ROOT.join(relative_dir)
  return [] unless root.directory?

  root.find
    .select { |path| path.file? && path.extname == ".swift" }
    .map { |path| path.relative_path_from(ROOT).to_s }
    .sort
end

